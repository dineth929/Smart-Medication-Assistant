def answer_question(question):
    """Return (text, kind). kind is 'ai', 'blocked' or 'emergency'.

    Blocked/emergency texts are local and work offline.
    """
    question = question.strip()
    if not question:
        raise AIError("Please type a question first.")
    if len(question) > 500:
        raise AIError("Please keep the question under 500 characters.")

    verdict = screen_question(question)
    if verdict == "emergency":
        return EMERGENCY_MESSAGE, verdict
    if verdict == "blocked":
        return BLOCKED_MESSAGE, verdict

    # Converted to Gemini's system_instruction & contents structure
    payload = {
        "system_instruction": {
            "parts": [{"text": SYSTEM_PROMPT}]
        },
        "contents": [{
            "role": "user",
            "parts": [{"text": f"<question>{question}</question>"}]
        }],
        "generationConfig": {
            "maxOutputTokens": 700,
            "temperature": 0.2
        }
    }

    text = _post(payload)
    return text, "ai"


def disclaimer_for():
    return DISCLAIMER


# ----------------------------------------------------------------------
# Prescription OCR (vision model; image is sent to the API, so the UI
# must get the user's consent first)
# ----------------------------------------------------------------------
_OCR_PROMPT = (
    "Transcribe all text visible in this prescription or medicine-label image, "
    "exactly as written, preserving line breaks. Do NOT correct, interpret, "
    "complete, or add anything. If a word or number is hard to read, write "
    "[unclear] instead of guessing. If the image contains no readable text, "
    "reply exactly: NO_TEXT_FOUND"
)


def _prepare_image(path):
    """Return (base64_data, media_type). Downscales big phone photos."""
    try:
        from PIL import Image, ImageOps
        image = ImageOps.exif_transpose(Image.open(path)).convert("RGB")
        image.thumbnail((1800, 1800))
        buffer = io.BytesIO()
        image.save(buffer, "JPEG", quality=85)
        return base64.b64encode(buffer.getvalue()).decode(), "image/jpeg"
    except ImportError:
        with open(path, "rb") as handle:
            raw = handle.read()
        if len(raw) > 4_500_000:
            raise AIError("Image is too large. Install Pillow or pick a "
                          "smaller photo.")
        media = "image/png" if path.lower().endswith(".png") else "image/jpeg"
        return base64.b64encode(raw).decode(), media
    except Exception as error:
        raise AIError("Could not open that image.") from error


def extract_prescription_text(image_path):
    data, media_type = _prepare_image(image_path)

    # Converted to Gemini inline_data multimodal payload
    payload = {
        "contents": [{
            "role": "user",
            "parts": [
                {
                    "inline_data": {
                        "mime_type": media_type,
                        "data": data
                    }
                },
                {"text": _OCR_PROMPT}
            ]
        }],
        "generationConfig": {
            "maxOutputTokens": 1500,
            "temperature": 0.0  # Zero temperature for deterministic transcription
        }
    }

    text = _post(payload)
    if text.strip() == "NO_TEXT_FOUND":
        raise AIError("No readable text was found. Try a clearer, well-lit photo.")
    return text